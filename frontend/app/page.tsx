type TestFocus = { requirement_id: string; test_case_id?: string; sequence: number; intent?: "existing" };
type TestFilter = "all" | "draft" | "ready" | "rejected";
function filterSavedTests(tests: SavedTestCase[], filter: TestFilter, requirementId: string, query: string, documentId: string) {
  const search = query.trim().toLowerCase();
  return tests.filter((test) => {
    const linkedIds = linkedRequirementIdsForDocument(test, documentId);
    return (requirementId === "all" || linkedIds.includes(requirementId)) &&
      (filter === "all" || (filter === "ready" ? test.status === "approved" || test.status === "ready" : test.status === filter)) &&
      (!search || `${test.test_case.title} ${linkedIds.join(" ")} ${test.test_case_id}`.toLowerCase().includes(search));
  });
}


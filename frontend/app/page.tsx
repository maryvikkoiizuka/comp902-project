      <p style={{ marginTop: "12px", color: "#596779", fontSize: "13px", lineHeight: 1.6 }}>Write a test for this existing requirement. Its REQ ID is already assigned; a unique test case ID is created when you save. Saving marks this manually authored test as ready, without a separate approval step. It remains editable.</p>

function csvCell(value: unknown) {
  const text = value == null ? "" : Array.isArray(value) ? value.join("\n") : String(value);
  return `"${text.replace(/"/g, '""')}"`;
}

function safeFilename(value: string) {
  const cleaned = value.trim().replace(/[^a-zA-Z0-9_-]+/g, "-").replace(/^-+|-+$/g, "");
  return cleaned || "export";
}

function downloadCsv(filename: string, headers: string[], rows: unknown[][]) {
  const csv = [headers, ...rows].map((row) => row.map(csvCell).join(",")).join("\r\n");
  const blob = new Blob(["\uFEFF", csv], { type: "text/csv;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  link.remove();
  URL.revokeObjectURL(url);
}

function linkedRequirementIdsForDocument(record: SavedTestCase, documentId: string) {
  if (record.linked_requirements?.length) {
    return record.linked_requirements.filter((link) => link.document_id === documentId).map((link) => link.requirement_id);
  }
  if (record.document_id === documentId) return record.linked_requirement_ids?.length ? record.linked_requirement_ids : [record.requirement_id];
  return [];
}

function exportSavedTestsCsv(tests: SavedTestCase[], documentTitle: string, documentId: string) {
  const headers = [
    "Test Case ID", "Requirement ID", "Title", "Status", "Origin", "Preconditions", "Test Data",
    "Steps", "Expected Result", "Assumptions", "Review Decision", "Review Note", "Reviewed At", "Created At",
  ];
  const rows = [...tests]
    .sort((a, b) => a.test_case_id.localeCompare(b.test_case_id, undefined, { numeric: true }))
    .map((record) => [
      record.test_case_id, linkedRequirementIdsForDocument(record, documentId).join("; "), record.test_case.title, record.status,
      record.origin === "manual_authored" ? "Manual" : "AI / submitted",
      record.test_case.preconditions, record.test_case.test_data,
      record.test_case.steps.map((step, index) => `${index + 1}. ${step}`),
      record.test_case.expected_result, record.test_case.assumptions,
      record.review?.decision ?? "", record.review?.note ?? "", record.review?.reviewed_at ?? "", record.created_at,
    ]);
  downloadCsv(`${safeFilename(documentTitle)}-test-cases.csv`, headers, rows);
}

function exportTraceabilityCsv(data: TraceabilityResponse) {
  const headers = [
    "Requirement ID", "Requirement", "Source Line", "Source Text", "Test Case ID", "Test Case Title",
    "Test Status", "Review Decision", "Review Note", "Reviewed At", "Test Created At",
  ];
  const rows = data.requirements.flatMap((requirement) => {
    if (!requirement.test_cases.length) {
      return [[requirement.requirement_id, requirement.text, requirement.source_line, requirement.source_text, "", "", "No tests", "", "", "", ""]];
    }
    return requirement.test_cases.map((test) => [
      requirement.requirement_id, requirement.text, requirement.source_line, requirement.source_text,
      test.test_case_id, test.title, test.status, test.review?.decision ?? "", test.review?.note ?? "",
      test.review?.reviewed_at ?? "", test.created_at,
    ]);
  });
  downloadCsv(`${safeFilename(data.title)}-traceability.csv`, headers, rows);
}

function RequirementSource({ requirement, documentId, refreshKey, actions }: {
  requirement: RequirementCoverage | null; documentId: string; refreshKey: number; actions?: ReactNode;
}) {
  const [sources, setSources] = useState<PreviewRequirement[]>([]);
  const [documentText, setDocumentText] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  useEffect(() => {
    const controller = new AbortController();
    setSources([]); setDocumentText(null); setError(null); setLoading(true);
    async function load() {
      try {
        const responses = await Promise.all([
          fetch(`${API_BASE}/requirements/documents/${encodeURIComponent(documentId)}/requirements`, { signal: controller.signal, cache: "no-store" }),
          fetch(`${API_BASE}/requirements/documents/${encodeURIComponent(documentId)}`, { signal: controller.signal, cache: "no-store" }),
        ]);
        if (!responses[0].ok || !responses[1].ok) throw new Error("Unable to load the stored document context. Refresh to retry.");
        const [requirements, document] = await Promise.all(responses.map((response) => response.json()));
        if (requirements.document_id !== documentId || document.document_id !== documentId || !Array.isArray(requirements.requirements) || typeof document.text !== "string") throw new Error("Unexpected source document response.");
        if (!controller.signal.aborted) { setSources(requirements.requirements); setDocumentText(document.text); }
      } catch (err) { if (!controller.signal.aborted) setError(err instanceof Error ? err.message : "Unable to load source context."); }
      finally { if (!controller.signal.aborted) setLoading(false); }
    }
    void load(); return () => controller.abort();
  }, [documentId, refreshKey]);
  const source = sources.find((item) => item.requirement_id === requirement?.requirement_id);
  const lines = documentText?.split(/\r?\n/) ?? [];
  const sourceIndex = source ? source.source_line - 1 : -1;
  const context = sourceIndex >= 0 && sourceIndex < lines.length && lines[sourceIndex].trim() === source?.source_text.trim()
    ? lines.map((text, index) => ({ text, line: index + 1 })).slice(Math.max(0, sourceIndex - 1), sourceIndex + 2) : [];
  return <>
    <section className="source-card" aria-label="Selected requirement">
      <div className="source-heading"><h3>{requirement?.requirement_id ?? "Select a requirement"}</h3>{source && <span className="source-citation">{source.filename ?? "Manual text"}{source.page != null ? ` · page ${source.page}` : ""} · {source.page != null ? `page line ${source.source_page_line ?? "—"}` : `document line ${source.source_line}`}</span>}</div>
      <p className="requirement-quote">{requirement?.text ?? "Choose a saved requirement to inspect its source."}</p>
      {actions}
    </section>
    {requirement && <section className="source-card document-context">
      <h3>Context in the document</h3><p className="muted">Read the stored source before deciding what to test.</p>
      {loading && <p role="status" className="muted">Loading document context…</p>}
      {error && <p role="alert" style={{ color: "#9d2929", marginTop: "16px" }}>{error}</p>}
      {context.length > 0 ? <div className="context-lines">{context.map((line) => <div key={line.line} className={line.line === source?.source_line ? "context-line active" : "context-line"}><span>L{line.line}</span><p>{line.text || "(Blank line)"}</p></div>)}</div> : source && <blockquote className="source-excerpt">{source.source_text}</blockquote>}
      {source && <details style={{ marginTop: "18px" }}><summary>Source details</summary><dl className="source-metadata"><dt>Document</dt><dd>{source.filename ?? "Manual text"}</dd>{source.page != null && <><dt>PDF page</dt><dd>{source.page}</dd></>}{source.source_page_line != null && <><dt>Page line</dt><dd>{source.source_page_line}</dd></>}<dt>Document line</dt><dd>{source.source_line}</dd></dl></details>}
    </section>}
  </>;
}


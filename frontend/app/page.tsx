function DocumentBrowser({ currentDocumentId, refreshKey, disabled, onOpen, onDeleted, onAdd, protectedDocumentId }: {
  currentDocumentId: string;
  refreshKey: number;
  disabled: boolean;
  onOpen: (documentId: string) => void;
  onDeleted: (documentId: string) => void;
  onAdd: () => void;
  protectedDocumentId?: string | null;
}) {
  const [searchInput, setSearchInput] = useState("");
  const [query, setQuery] = useState("");
  const [offset, setOffset] = useState(0);
  const [refresh, setRefresh] = useState(0);
  const [data, setData] = useState<DocumentsResponse | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [confirmId, setConfirmId] = useState<string | null>(null);
  const [deletingId, setDeletingId] = useState<string | null>(null);
  const [deleteError, setDeleteError] = useState<string | null>(null);
  const [deleteMessage, setDeleteMessage] = useState<string | null>(null);
  const deleteController = useRef<AbortController | null>(null);
  useEffect(() => () => deleteController.current?.abort(), []);
  const pageSize = 12;

  useEffect(() => {
    const controller = new AbortController();
    setLoading(true);
    setError(null);
    setData(null);
    async function loadDocuments() {
      try {
        const parameters = new URLSearchParams({ query, offset: String(offset), limit: String(pageSize) });
        const response = await fetch(`${API_BASE}/requirements/documents?${parameters}`, { cache: "no-store", signal: controller.signal });
        if (!response.ok) throw new Error(`Could not load documents (HTTP ${response.status}). Check that the backend is running.`);
        const result: DocumentsResponse = await response.json();
        if (!Array.isArray(result.documents) || !Number.isInteger(result.total_count) || result.total_count < 0 ||
          result.offset !== offset || result.limit !== pageSize || !result.documents.every((item) =>
            item && typeof item.document_id === "string" && typeof item.title === "string" && typeof item.created_at === "string" &&
            Number.isInteger(item.requirement_count) && item.requirement_count >= 0)) {
          throw new Error("The backend returned incomplete document list details.");
        }
        if (!controller.signal.aborted) {
          if (offset > 0 && result.documents.length === 0 && result.total_count > 0) {
            setOffset(Math.floor((result.total_count - 1) / pageSize) * pageSize);
          } else setData(result);
        }
      } catch (caught) {
        if (!controller.signal.aborted) setError(caught instanceof TypeError
          ? "Could not reach the backend. Start FastAPI, then refresh the document list."
          : caught instanceof Error ? caught.message : "Unable to load documents.");
      } finally {
        if (!controller.signal.aborted) setLoading(false);
      }
    }
    void loadDocuments();
    return () => controller.abort();
  }, [query, offset, refresh, refreshKey]);

  async function deleteDocument(item: DocumentSummary) {
    if (deleteController.current || disabled || confirmId !== item.document_id || protectedDocumentId === item.document_id) return;
    const controller = new AbortController();
    deleteController.current = controller;
    setDeletingId(item.document_id);
    setDeleteError(null);
    setDeleteMessage(null);
    try {
      const response = await fetch(`${API_BASE}/requirements/documents/${encodeURIComponent(item.document_id)}`, { method: "DELETE", signal: controller.signal });
      if (!response.ok) {
        let message = `Deletion failed (HTTP ${response.status}).`;
        try { const body = await response.json(); if (typeof body.detail === "string") message = body.detail; } catch { /* Keep HTTP message. */ }
        throw new Error(message);
      }
      const result = await response.json();
      if (result.document_id !== item.document_id || result.deleted !== true) throw new Error("The response did not confirm deletion. Refresh documents to check before retrying.");
      if (!controller.signal.aborted) {
        setConfirmId(null);
        setDeleteMessage(`Deleted “${item.title}” and its related records.`);
        setRefresh((value) => value + 1);
        onDeleted(item.document_id);
      }
    } catch (caught) {
      if (!controller.signal.aborted) setDeleteError(caught instanceof TypeError
        ? "The deletion response was not received. Refresh documents to check the result; retrying deletion is safe if the document remains."
        : caught instanceof Error ? caught.message : "Unable to delete document.");
    } finally {
      if (deleteController.current === controller) {
        deleteController.current = null;
        if (!controller.signal.aborted) setDeletingId(null);
      }
    }
  }

  return (
    <section aria-labelledby="documents-heading" className="documents-screen">
      <div style={{ display: "flex", justifyContent: "space-between", alignItems: "center", gap: "14px", flexWrap: "wrap" }}>
        <div>
          <h1 id="documents-heading" className="screen-title">Documents</h1>
          <p style={{ marginTop: "8px", fontSize: "14px", color: "#596779" }}>Turn requirements into traceable tests.</p>
        </div>
        <div className="document-header-actions">
          <button type="button" disabled={loading || deletingId !== null} onClick={() => setRefresh((value) => value + 1)} className="modern-button secondary">Refresh</button>
          <button type="button" disabled={disabled || deletingId !== null} onClick={onAdd} className="modern-button primary">＋ Add document</button>
        </div>
      </div>
      <form onSubmit={(event) => { event.preventDefault(); setQuery(searchInput.trim()); setOffset(0); setRefresh((value) => value + 1); }}
        style={{ display: "flex", gap: "10px", marginTop: "20px", flexWrap: "wrap" }}>
        <label style={{ flex: "0 1 420px", fontSize: "13px", fontWeight: 600 }}>
          Search documents
          <input type="search" value={searchInput} onChange={(event) => setSearchInput(event.target.value)} placeholder="Search by title or filename…"
            maxLength={200} style={{ display: "block", marginTop: "7px", boxSizing: "border-box", width: "100%", padding: "11px 12px", border: "1px solid #bac5d2", borderRadius: "8px", color: "#1c293b", background: "#ffffff", fontFamily: "inherit" }} />
        </label>
        <button type="submit" disabled={deletingId !== null} style={{ ...buttonStyle, alignSelf: "flex-end" }}>Search</button>
        {query && <button type="button" onClick={() => { setSearchInput(""); setQuery(""); setOffset(0); }} style={{ ...buttonStyle, alignSelf: "flex-end", background: "#ffffff", color: "#24634f" }}>Clear search</button>}
      </form>
      {deleteMessage && <p role="status" style={{ marginTop: "16px", color: "#17623b" }}>{deleteMessage}</p>}
      {deleteError && <p role="alert" style={{ marginTop: "16px", padding: "14px", background: "#fde9e9", color: "#9d2929", borderRadius: "8px" }}>{deleteError}</p>}
      {loading && <p role="status" style={{ marginTop: "20px" }}>Loading documents...</p>}
      {error && <p role="alert" style={{ marginTop: "20px", padding: "14px", background: "#fde9e9", color: "#9d2929", borderRadius: "8px" }}>{error}</p>}
      {data && <>
        <p role="status" style={{ marginTop: "16px", fontSize: "13px", color: "#596779" }}>
          {data.total_count} {query ? "matching" : "saved"} {data.total_count === 1 ? "document" : "documents"}. Newest first.
        </p>
        {data.documents.length === 0 ? <p style={{ marginTop: "16px", padding: "20px", background: "#f3f6fa", borderRadius: "8px" }}>{query ? "No documents match this search. Try another title or filename." : "No documents saved yet. Use Add a document below to get started."}</p> :
          <div className="modern-document-grid">
            {data.documents.map((item) => {
              const selected = item.document_id === currentDocumentId;
              const date = new Date(item.created_at);
              return <article key={item.document_id} className={`modern-document-card${selected ? " selected" : ""}`}>
                <div style={{ display: "flex", justifyContent: "space-between", gap: "8px", fontSize: "12px", color: "#596779", marginBottom: "10px" }}>
                  <span className="document-type">{item.source_type === "pdf" ? "PDF" : "Manual text"}</span>
                  {selected && <strong style={{ color: "#24634f" }}>Selected</strong>}
                </div>
                <h3 style={{ fontSize: "16px", fontWeight: 700, overflowWrap: "anywhere", lineHeight: 1.5 }}>{item.title}</h3>
                {item.filename && <p style={{ marginTop: "8px", color: "#596779", fontSize: "12px", overflowWrap: "anywhere" }}>{item.filename}{item.page_count != null ? ` · ${item.page_count} pages` : ""}</p>}
                <p style={{ marginTop: "12px", fontSize: "12px", color: "#596779" }}>Added {Number.isNaN(date.getTime()) ? item.created_at : date.toLocaleString()}</p>
                {!item.filename && <p className="muted">Entered manually</p>}
                <DocumentCardCoverage documentId={item.document_id} refreshKey={refreshKey + refresh} />
                <button type="button" disabled={disabled || deletingId !== null || confirmId !== null} onClick={() => onOpen(item.document_id)} className="modern-button secondary" style={{ marginTop: "12px", width: "100%" }}>Open workspace</button>
                <button type="button" disabled={disabled || deletingId !== null || protectedDocumentId === item.document_id} title={protectedDocumentId === item.document_id ? "Cancel waiting before deleting the document being processed" : undefined} onClick={() => { setConfirmId(item.document_id); setDeleteError(null); setDeleteMessage(null); }}
                  style={{ marginTop: "12px", padding: "4px 0", background: "transparent", border: 0, color: "#9d2929", fontSize: "12px", cursor: "pointer" }}>Delete document</button>
                {confirmId === item.document_id && <div role="group" aria-label={`Confirm deleting ${item.title}`} style={{ marginTop: "14px", padding: "14px", background: "#fff2f2", border: "1px solid #e7b8b8", borderRadius: "8px", fontSize: "13px", lineHeight: 1.6 }}>
                  <strong>Delete “{item.title}”?</strong>
                  {item.filename && <p style={{ overflowWrap: "anywhere" }}>File: {item.filename}</p>}
                  <p style={{ marginTop: "8px" }}>This permanently removes the saved source, original PDF, requirements, test cases, reviews, and associated search vectors. It cannot be undone.</p>
                  <div style={{ display: "flex", gap: "8px", flexWrap: "wrap", marginTop: "12px" }}>
                    <button type="button" disabled={disabled || deletingId !== null || protectedDocumentId === item.document_id} onClick={() => void deleteDocument(item)} style={{ ...buttonStyle, background: "#9d2929", borderColor: "#9d2929", fontSize: "12px" }}>{deletingId === item.document_id ? "Deleting..." : "Delete permanently"}</button>
                    <button type="button" disabled={deletingId !== null} onClick={() => { setConfirmId(null); setDeleteError(null); }} style={{ ...buttonStyle, background: "#ffffff", color: "#24634f", fontSize: "12px" }}>Cancel</button>
                  </div>
                </div>}
              </article>;
            })}
          </div>}
        {data.total_count > pageSize && <div style={{ display: "flex", alignItems: "center", gap: "12px", marginTop: "18px", flexWrap: "wrap" }}>
          <button type="button" disabled={offset === 0} onClick={() => setOffset((value) => Math.max(0, value - pageSize))} style={{ ...buttonStyle, background: "#ffffff", color: "#24634f" }}>Previous</button>
          <span style={{ fontSize: "13px" }}>Page {Math.floor(offset / pageSize) + 1} of {Math.ceil(data.total_count / pageSize)}</span>
          <button type="button" disabled={offset + pageSize >= data.total_count} onClick={() => setOffset((value) => value + pageSize)} style={buttonStyle}>Next</button>
        </div>}
      </>}
    </section>
  );
}

